export const getI18n = (language) => I18N[language] || I18N[DEFAULT_LANGUAGE];

export const getSpecialityLabel = (value, language, type = 'labels') => {
  const option = SPECIALITY_OPTIONS.find((item) => item.value === value);
  if (!option) return value;
  const fallback = option[type]?.fr;
  return option[type]?.[language] || fallback || value;
};

export const getSectorLabel = (value, language) => {
  const option = SECTOR_OPTIONS.find((item) => item.value === value);
  if (!option) return value;
  return option.labels[language] || option.labels.fr || value;
};
